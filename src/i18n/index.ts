const dictionaries: Record<Locale, Dict> = { zh, en };

/** Sorted keys of a locale's dictionary — used by the translation-parity test. */
export function translationKeys(locale: Locale): string[] {
  return Object.keys(dictionaries[locale]).sort();
}

interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  locale: "zh",
  setLocale: (locale) => set({ locale }),
}));

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const table = dictionaries[locale] ?? dictionaries.zh;
  let text = table[key] ?? dictionaries.zh[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** React hook: `const t = useT(); t("nav.home")` */
export function useT() {
  const locale = useI18nStore((s) => s.locale);
  return (key: string, vars?: Record<string, string | number>) => translate(locale, key, vars);
}

export function useLocale(): Locale {
  return useI18nStore((s) => s.locale);
}
