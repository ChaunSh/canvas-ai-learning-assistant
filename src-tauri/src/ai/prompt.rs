//! Prompt construction and citation handling.
//!
//! Two rules drive this module:
//!   1. Document text is *evidence*, never instruction. Retrieved material is
//!      wrapped in an explicit untrusted block so a malicious PDF cannot turn
//!      itself into a system prompt (§55).
//!   2. Every citation the UI shows must map back to a chunk that retrieval
//!      actually returned (§29). We never invent a source or a page number.

use std::collections::{HashMap, HashSet};

use crate::domain::{Citation, SearchHit};

/// Context budget for retrieved chunks, in approximate tokens.
pub const DEFAULT_CONTEXT_TOKENS: i64 = 6000;

