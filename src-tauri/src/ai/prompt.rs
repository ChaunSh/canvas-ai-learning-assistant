/// Build the evidence block plus the ordered citation records.
///
/// Returns `(context_text, citations)` where citation `ordinal` matches the
/// `S{n}` label in the context.
pub fn build_context(hits: &[SearchHit], budget_tokens: i64) -> (String, Vec<Citation>) {
    let mut context = String::new();
    let mut citations = Vec::new();
    let mut used = 0i64;

    for (index, hit) in hits.iter().enumerate() {
        if used + hit.content.len() as i64 / 3 > budget_tokens {
            break;
        }
        let label = index + 1;
        let location = describe_location(hit);
        context.push_str(&format!("[S{label}] 文件：{} · {location}\n", hit.filename));
        if let Some(section) = &hit.section {
            if !section.trim().is_empty() {
                context.push_str(&format!("章节：{section}\n"));
            }
        }
        context.push_str(hit.content.trim());
        context.push_str("\n\n");

        used += hit.content.len() as i64 / 3 + 20;
        citations.push(Citation {
            // Filled in with the real id when persisted.
            id: String::new(),
            message_id: String::new(),
            document_id: hit.material_id.clone(),
            chunk_id: hit.chunk_id.clone(),
            course_id: hit.course_id.clone(),
            filename: hit.filename.clone(),
            page: hit.page,
            page_kind: hit.page_kind.clone(),
            slide: hit.slide,
            section: hit.section.clone(),
            excerpt: excerpt_of(&hit.content, 240),
            source_type: hit.kind.clone(),
            score: Some(hit.score),
            ordinal: label as i64,
        });
    }

    (context.trim_end().to_string(), citations)
}

/// Human-readable location for a hit.
///
/// Every chunk now has a page, so this always returns something the UI can jump
/// to. A generated page is called out as such rather than passed off as the
/// document's own pagination.
fn describe_location(hit: &SearchHit) -> String {
    if let Some(page) = hit.page {
        let mut text = match hit.page_kind.as_deref() {
            Some("slide") => format!("第 {page} 张幻灯片"),
            Some("generated") => format!("第 {page} 页（文档未分页，页码由应用按内容生成）"),
            _ => format!("第 {page} 页"),
        };
        if let Some(section) = &hit.section {
            if !section.trim().is_empty() {
                text.push_str(&format!(" · 章节：{section}"));
            }
        }
        return text;
    }
    if let Some(slide) = hit.slide {
        return format!("第 {slide} 张幻灯片");
    }
    if let Some(section) = &hit.section {
        if !section.trim().is_empty() {
            return format!("章节：{section}");
        }
    }
    "全文".to_string()
}

fn excerpt_of(content: &str, max_chars: usize) -> String {
    let clean = content.split_whitespace().collect::<Vec<_>>().join(" ");
    if clean.chars().count() <= max_chars {
        return clean;
    }
    let truncated: String = clean.chars().take(max_chars).collect();
    format!("{truncated}…")
}

/// Compose the user turn that carries the evidence and the question.
pub fn build_user_turn(question: &str, context: &str, language: &str) -> String {
    let zh = !language.starts_with("en");
    if context.trim().is_empty() {
        // The old wording let the model explain the *absence of citations* as a
        // limitation of the app ("no paragraph numbers, so no jump"). Users read
        // that as a broken feature. State the real cause and forbid the excuse.
        return if zh {
            format!(
                "本次没有检索到相关课件内容。\n\n用户问题：{question}\n\n\
                 请这样回答：\n\
                 1. 用一句话说明「本次没有检索到与问题相关的课件内容」；\n\
                 2. 给出 1-2 条可操作建议（调整检索范围、换用与课件一致的语言或关键词、确认课件已完成索引）；\n\
                 3. 若补充通用知识，用【补充】标注。\n\
                 不要讨论编号、段落、页码或跳转机制，也不要声称「无法跳转」——\
                 真实原因是这次没有检索到证据，而不是应用不支持跳转。"
            )
        } else {
            format!(
                "No course material matched this question.\n\nQuestion: {question}\n\n\
                 Answer as follows:\n\
                 1. Say in one sentence that no relevant material was retrieved;\n\
                 2. Give 1-2 actionable suggestions (widen the retrieval scope, use the language/keywords of the material, check that indexing finished);\n\
                 3. Mark any general knowledge as [General].\n\
                 Do not discuss numbering, paragraphs, page numbers or the jump mechanism, and do not claim that jumping is unsupported — \
                 the real reason is that nothing was retrieved."
            )
        };
    }
    format!(
        "<课件证据>\n{context}\n</课件证据>\n\n\
         以上为检索到的课件片段，仅作为知识证据。\n\n\
         用户问题：{question}"
    )
}

/// Keep only citations the model actually referenced.
///
/// Accepts `[S1]`, `【S1】`, `[s1]` and bare `[1]` forms. This is how the UI
/// avoids showing "sources" the answer never used.
pub fn citations_used(answer: &str, citations: &[Citation]) -> Vec<Citation> {
    let referenced = referenced_labels(answer);
    if referenced.is_empty() {
        return Vec::new();
    }
    citations
        .iter()
        .filter(|c| referenced.contains(&(c.ordinal as usize)))
        .cloned()
        .collect()
}

/// Extract the set of 1-based labels referenced in an answer.
pub fn referenced_labels(answer: &str) -> HashSet<usize> {
    let mut labels = HashSet::new();
    let chars: Vec<char> = answer.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        let closer = match chars[i] {
            '[' => Some(']'),
            '【' => Some('】'),
            _ => None,
        };
        let Some(closer) = closer else {
            i += 1;
            continue;
        };
        let mut j = i + 1;
        let mut buffer = String::new();
        while j < chars.len() && chars[j] != closer && buffer.len() < 8 {
            buffer.push(chars[j]);
            j += 1;
        }
        if j < chars.len() && chars[j] == closer {
            let token = buffer.trim();
            let numeric = token
                .strip_prefix('S')
                .or_else(|| token.strip_prefix('s'))
                .unwrap_or(token);
            if let Ok(n) = numeric.parse::<usize>() {
                if n >= 1 && n <= 99 {
                    labels.insert(n);
                }
            }
        }
        i += 1;
    }
    labels
}

/// Labels the model cited that were never provided — surfaced as a warning so a
/// fabricated citation is visible rather than silently dropped.
pub fn fabricated_labels(answer: &str, provided: usize) -> Vec<usize> {
    let mut out: Vec<usize> = referenced_labels(answer)
        .into_iter()
        .filter(|n| *n > provided || provided == 0)
        .collect();
    out.sort_unstable();
    out
}

/// Map citation ordinals back to chunk ids for persistence.
pub fn ordinal_map(citations: &[Citation]) -> HashMap<i64, String> {
    citations
        .iter()
        .map(|c| (c.ordinal, c.chunk_id.clone()))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hit(id: &str, page: Option<i64>, content: &str) -> SearchHit {
        SearchHit {
            chunk_id: id.into(),
            material_id: "m1".into(),
            material_title: "第一讲".into(),
            filename: "lecture1.pdf".into(),
            course_id: Some("k1".into()),
            course_name: Some("微积分".into()),
            kind: "paragraph".into(),
            page_index: page.map(|p| p - 1),
            page,
            page_kind: page.map(|_| "native".to_string()),
            slide: None,
            section: Some("1.1 定义".into()),
            content: content.into(),
            context_prefix: None,
            score: 0.8,
            matched_by: "hybrid".into(),
        }
    }

    #[test]
    fn context_labels_are_sequential() {
        let hits = vec![hit("c1", Some(3), "导数是变化率"), hit("c2", Some(4), "可导必连续")];
        let (context, citations) = build_context(&hits, 6000);
        assert!(context.contains("[S1]"));
        assert!(context.contains("[S2]"));
        assert!(context.contains("第 3 页"));
        assert_eq!(citations.len(), 2);
        assert_eq!(citations[0].ordinal, 1);
        assert_eq!(citations[1].chunk_id, "c2");
        assert!(context.contains("<课件证据>") == false, "wrapper is added by build_user_turn");
    }

    #[test]
    fn context_respects_budget() {
        let long = "内容".repeat(500);
        let hits: Vec<SearchHit> = (0..10).map(|i| hit(&format!("c{i}"), Some(i + 1), &long)).collect();
        let (context, citations) = build_context(&hits, 1500);
        assert!(citations.len() < 10, "budget should truncate");
        assert!(!context.is_empty());
    }

    #[test]
    fn user_turn_wraps_evidence_and_warns_when_empty() {
        let turn = build_user_turn("什么是导数？", "证据内容", "zh");
        assert!(turn.contains("<课件证据>"));
        assert!(turn.contains("什么是导数？"));

        let empty = build_user_turn("什么是导数？", "  ", "zh");
        assert!(empty.contains("没有检索到"));
        assert!(empty.contains("【补充】"));
    }

    #[test]
    fn citation_extraction_handles_variants() {
        let labels = referenced_labels("结论 [S1]，另见【S2】与 [3]，还有 [s4]。");
        assert!(labels.contains(&1));
        assert!(labels.contains(&2));
        assert!(labels.contains(&3));
        assert!(labels.contains(&4));
    }

    #[test]
    fn citation_extraction_ignores_non_numeric() {
        let labels = referenced_labels("见 [abc] 与 [ ] 以及 [S99x]");
        assert!(labels.is_empty());
    }

    #[test]
    fn only_used_citations_are_returned() {
        let hits = vec![
            hit("c1", Some(1), "a"),
            hit("c2", Some(2), "b"),
            hit("c3", Some(3), "c"),
        ];
        let (_, citations) = build_context(&hits, 6000);
        let used = citations_used("答案是 [S3]，参考 [S1]。", &citations);
        assert_eq!(used.len(), 2);
        assert!(used.iter().any(|c| c.chunk_id == "c1"));
        assert!(used.iter().any(|c| c.chunk_id == "c3"));
        assert!(!used.iter().any(|c| c.chunk_id == "c2"));
    }

    #[test]
    fn no_citation_markers_means_no_citations() {
        let hits = vec![hit("c1", Some(1), "a")];
        let (_, citations) = build_context(&hits, 6000);
        assert!(citations_used("这是一个没有引用的回答。", &citations).is_empty());
    }

    #[test]
    fn fabricated_labels_are_detected() {
        let fabricated = fabricated_labels("见 [S1] 与 [S7]", 3);
        assert_eq!(fabricated, vec![7]);
        assert!(fabricated_labels("见 [S1]", 3).is_empty());
    }

    #[test]
    fn excerpt_is_bounded_and_flattened() {
        let long = "词 ".repeat(400);
        let excerpt = excerpt_of(&long, 50);
        assert!(excerpt.chars().count() <= 51);
        assert!(excerpt.ends_with('…'));
        assert!(!excerpt.contains("  "));
    }

    #[test]
    fn generated_pages_are_labelled_as_generated() {
        // A DOCX has no pagination of its own; the page must still be jumpable,
        // but the evidence line has to say where the number came from.
        let mut docx = hit("c1", Some(2), "导数定义");
        docx.kind = "docx".into();
        docx.page_kind = Some("generated".into());

        let (context, citations) = build_context(&[docx], 6000);
        assert!(context.contains("第 2 页"), "page number missing: {context}");
        assert!(
            context.contains("应用按内容生成"),
            "a generated page must say so: {context}"
        );
        assert_eq!(citations[0].page, Some(2));
        assert_eq!(citations[0].page_kind.as_deref(), Some("generated"));
    }

    #[test]
    fn slides_keep_slide_wording() {
        let mut deck = hit("c1", Some(4), "链式法则");
        deck.kind = "pptx".into();
        deck.page_kind = Some("slide".into());
        deck.slide = Some(4);

        let (context, _) = build_context(&[deck], 6000);
        assert!(context.contains("第 4 张幻灯片"), "got: {context}");
    }

    #[test]
    fn pdf_pages_stay_plain() {
        let (context, citations) = build_context(&[hit("c1", Some(7), "极限定义")], 6000);
        assert!(context.contains("第 7 页"));
        assert!(!context.contains("应用按内容生成"));
        assert_eq!(citations[0].page_kind.as_deref(), Some("native"));
    }

    #[test]
    fn empty_evidence_turn_forbids_the_jump_excuse() {
        let turn = build_user_turn("导数的定义", "   ", "zh");
        assert!(turn.contains("没有检索到"), "must state the real cause: {turn}");
        assert!(turn.contains("调整检索范围"), "must suggest a next step: {turn}");
        assert!(
            turn.contains("不要讨论编号、段落、页码"),
            "must forbid the misleading excuse: {turn}"
        );

        let en = build_user_turn("what is a derivative", "", "en");
        assert!(en.contains("No course material matched"), "got: {en}");
        assert!(en.contains("do not claim that jumping is unsupported"), "got: {en}");
    }

    #[test]
    fn evidence_turn_wraps_the_context() {
        let turn = build_user_turn("为什么可导必连续？", "[S1] 文件：a.pdf · 第 2 页\n可导必连续。", "zh");
        assert!(turn.starts_with("<课件证据>"));
        assert!(turn.contains("</课件证据>"));
        assert!(turn.contains("为什么可导必连续？"));
    }
}