# Build an Android APK without Developer Mode.
#
# Why this script exists: `tauri android build` symlinks the compiled
# `libcanvas_ai_assistant_lib.so` into `gen/android/app/src/main/jniLibs/<abi>/`.
# Creating symlinks on Windows requires Developer Mode or
# SeCreateSymbolicLinkPrivilege; in a non-admin session neither is available, so
# the CLI aborts with:
#
#   Creation symbolic link is not allowed for this system.
#
# This script performs the same steps the CLI would, but *copies* the library and
# then calls Gradle with the Rust build tasks excluded (they are already done).
#
#   powershell -File scripts/build-android.ps1
#   powershell -File scripts/build-android.ps1 -Abis arm64-v8a
#   powershell -File scripts/build-android.ps1 -Release

param(
    [string[]]$Abis = @("arm64-v8a", "x86_64"),
    [switch]$Release
)

$ErrorActionPreference = "Stop"

$repo = Split-Path -Parent $PSScriptRoot
$tauriDir = Join-Path $repo "src-tauri"
$androidDir = Join-Path $tauriDir "gen/android"
$libName = "libcanvas_ai_assistant_lib.so"

$abiToTarget = @{
    "arm64-v8a"   = "aarch64-linux-android"
    "armeabi-v7a" = "armv7-linux-androideabi"
    "x86"         = "i686-linux-android"
    "x86_64"      = "x86_64-linux-android"
}

if (-not $env:NDK_HOME) {
    Write-Error "NDK_HOME is not set. Dot-source scripts/env.ps1 first (or run this script through it)."
}

$buildType = if ($Release) { "release" } else { "debug" }
$cargoProfile = if ($Release) { "--release" } else { "" }

foreach ($abi in $Abis) {
    if (-not $abiToTarget.ContainsKey($abi)) {
        Write-Error "Unknown ABI '$abi'. Known: $($abiToTarget.Keys -join ', ')"
    }
    $target = $abiToTarget[$abi]
    Write-Output "==> cargo build --target $target ($buildType)"
    Push-Location $tauriDir
    try {
        # Run through cmd: PowerShell 5.1 converts native stderr into terminating
        # errors when $ErrorActionPreference is "Stop".
        $cargoCmd = "cargo build --package canvas-ai-assistant --lib --target $target --features tauri/custom-protocol"
        if ($Release) { $cargoCmd += " --release" }
        $cargoLog = Join-Path $env:TEMP "cargo-android-$abi.log"
        & cmd /c "$cargoCmd 1> `"$cargoLog`" 2>&1"
        if ($LASTEXITCODE -ne 0) {
            Get-Content $cargoLog -Tail 30
            throw "cargo build failed for $target"
        }
    }
    finally {
        Pop-Location
    }

    $soPath = Join-Path $env:CARGO_TARGET_DIR "$target\$buildType\$libName"
    if (-not (Test-Path $soPath)) {
        throw "expected library not found: $soPath"
    }
    $destDir = Join-Path $androidDir "app/src/main/jniLibs/$abi"
    New-Item -ItemType Directory -Force -Path $destDir | Out-Null
    Copy-Item -Path $soPath -Destination (Join-Path $destDir $libName) -Force
    Write-Output "    staged $abi/$libName"
}

# The Rust build tasks would call the Tauri CLI again (and fail on symlinks), so
# they are excluded: jniLibs is already populated above. Task names follow the
# `arch` list declared by the generated Gradle plugin (note `X86_64`, not `X8664`).
$profileCapitalized = if ($Release) { "Release" } else { "Debug" }
$exclude = @(
    "-x", "rustBuildUniversal$profileCapitalized",
    "-x", "rustBuildArm64$profileCapitalized",
    "-x", "rustBuildArm$profileCapitalized",
    "-x", "rustBuildX86$profileCapitalized",
    "-x", "rustBuildX86_64$profileCapitalized"
)

$gradleTask = if ($Release) { "assembleUniversalRelease" } else { "assembleUniversalDebug" }

# Gradle resolves Android dependencies from Google's Maven repo, which is blocked
# on some networks. When env.ps1 has exported a proxy, hand it to Gradle's JVM.
$proxySource = if ($env:HTTPS_PROXY) { $env:HTTPS_PROXY } elseif ($env:HTTP_PROXY) { $env:HTTP_PROXY } else { $null }
if ($proxySource) {
    try {
        $uri = [Uri]$proxySource
        if ($uri.Host) {
            $env:GRADLE_OPTS = "$($env:GRADLE_OPTS) -Dhttp.proxyHost=$($uri.Host) -Dhttp.proxyPort=$($uri.Port) -Dhttps.proxyHost=$($uri.Host) -Dhttps.proxyPort=$($uri.Port)"
            Write-Output "==> using proxy $($uri.Host):$($uri.Port) for Gradle"
        }
    } catch {
        Write-Output "==> could not parse proxy '$proxySource'; Gradle will use direct connections"
    }
}

Write-Output "==> gradlew $gradleTask -PabiList=$($Abis -join ',')"
Push-Location $androidDir
try {
    # `gradlew.bat` is generated by `tauri android init`.
    & cmd /c "gradlew.bat $gradleTask -PabiList=$($Abis -join ',') -Pkotlin.incremental=false $($exclude -join ' ') 1> `"$env:TEMP\gradle-android.log`" 2>&1"
    $code = $LASTEXITCODE
    Get-Content "$env:TEMP\gradle-android.log" -Tail 25
    if ($code -ne 0) { throw "gradle failed with exit code $code" }
}
finally {
    Pop-Location
}

$apkDir = Join-Path $androidDir "app/build/outputs/apk"
if (Test-Path $apkDir) {
    Get-ChildItem $apkDir -Recurse -Filter "*.apk" | ForEach-Object {
        Write-Output "APK: $($_.FullName) ($([math]::Round($_.Length / 1MB, 2)) MiB)"
    }
}
